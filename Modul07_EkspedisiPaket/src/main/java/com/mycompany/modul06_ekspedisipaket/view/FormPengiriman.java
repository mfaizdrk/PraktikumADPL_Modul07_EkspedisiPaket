    private void siapkanForm(){
        tblRiwayat.setModel(modelTable);
        cbLayanan.removeAllItems();
        for(LayananPengiriman layananPengiriman : daftarLayanan){
            cbLayanan.addItem(layananPengiriman.getNama());
        }
        
        aturAsuransi();
        tampilkanRiwayat();
    }
    
    private void aturAsuransi(){
        int indeks = cbLayanan.getSelectedIndex();
        if(indeks < 0){
            return;
        }
        boolean bisaAsuransi = daftarLayanan.get(indeks) instanceof BisaDiasuransikan;
        chkAsuransi.setEnabled(bisaAsuransi);
        if(!bisaAsuransi){
            chkAsuransi.setSelected(false);
        }
    }
    
    private void simpan(){
        try{
            double berat = Double.parseDouble(tfBerat.getText().trim().replace(',', '.'));
            LayananPengiriman layanan = daftarLayanan.get(cbLayanan.getSelectedIndex());
            
            Pengiriman hasil = service.kirim(tfPenerima.getText(), berat, layanan, chkAsuransi.isSelected());
            
            lbTotal.setText("Total Ongkir: " + rupiah(hasil.getTotalOngkir()));
            
            tampilkanRiwayat();
        } catch (NumberFormatException e){
            JOptionPane.showConfirmDialog(this, "Berat harus berupa angka, contoh: 2 atau 1.5", "Input Tidak Valid", JOptionPane.WARNING_MESSAGE);
        } catch (IllegalArgumentException e){
            JOptionPane.showConfirmDialog(this, e.getMessage(), "Input Tidak Valid.", JOptionPane.WARNING_MESSAGE);
        }
    }
    
    private String angka(double nilai){
        return NumberFormat.getNumberInstance(INDONESIA).format(nilai);
    }
    
    private String rupiah(double nilai){
        NumberFormat format = NumberFormat.getNumberInstance(INDONESIA);
        format.setMaximumFractionDigits(0);
        return "Rp." + format.format(nilai);
    }
    
    private void tampilkanRiwayat(){
        modelTable.setRowCount(0);
        int no = 1;
        for (Pengiriman p : service.ambilRiwayat()){
            modelTable.addRow(new Object[]{
                no++,
                p.getPenerima(), 
                p.getNamaLayanan(), 
                angka(p.getBerat()), 
                p.isPakaiAsuransi() ? "Ya" : "Tidak", 
                rupiah(p.getTotalOngkir())
            });
        }
    }
    
    private void bersihkan(){
        tfPenerima.setText("");
        tfBerat.setText("");
        cbLayanan.setSelectedIndex(0);
        chkAsuransi.setSelected(false);
        lbTotal.setText("Total Ongkir: Rp0");
    }

